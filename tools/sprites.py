#!/usr/bin/env python3
"""
Turns source art into game sprites and wires them in.

    python3 tools/sprites.py            # process new or changed art
    python3 tools/sprites.py --force    # reprocess everything
    python3 tools/sprites.py --knockout # also clear a solid background

For every form in src/js/forms.js that has `assets/source/<id>.png`:
crop to the alpha bounds, resize to 900px wide and save
`assets/pet/<id>.webp`.

For every action in src/js/config.js that has
`assets/source/icons/<action>.png`: crop to the alpha bounds, centre on a
square canvas, resize to 256px and save `assets/icons/<action>.webp`.

Then rewrite src/js/sprites.js with the forms and actions that have art, so
the game picks them up, and print what is still missing.

Image generators sometimes paint a white or flat background instead of real
transparency. The script warns when the corners are opaque; --knockout
flood-fills that background away from the four corners.

Needs Pillow (pip install pillow).
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/source'
PET = ROOT / 'assets/pet'
ICON_SOURCE = ROOT / 'assets/source/icons'
ICONS = ROOT / 'assets/icons'
FORMS = ROOT / 'src/js/forms.js'
CONFIG = ROOT / 'src/js/config.js'
MANIFEST = ROOT / 'src/js/sprites.js'

WIDTH = 900
ICON_SIZE = 256
KNOCKOUT_THRESHOLD = 40  # colour distance still counted as background
OPAQUE = 16              # corner alpha above this means a painted background


def form_ids():
    """Form ids in the order forms.js lists them."""
    return re.findall(r"^form\('([^']+)'", FORMS.read_text(encoding='utf-8'), re.M)


def action_ids():
    """Action ids in ACTION_ORDER, as config.js lists them."""
    m = re.search(r"ACTION_ORDER = \[([^\]]*)\]", CONFIG.read_text(encoding='utf-8'))
    return re.findall(r"'([^']+)'", m.group(1))


def opaque_corners(im):
    w, h = im.size
    corners = [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]
    return [c for c in corners if im.getpixel(c)[3] > OPAQUE]


def knockout(im):
    for corner in opaque_corners(im):
        if im.getpixel(corner)[3] > OPAQUE:  # an earlier fill may have cleared it
            ImageDraw.floodfill(im, corner, (0, 0, 0, 0), thresh=KNOCKOUT_THRESHOLD)
    return im


def load(fid, src, clear):
    """Opens a source image cropped to its alpha bounds, or None if it is empty."""
    im = Image.open(src).convert('RGBA')
    if clear:
        knockout(im)
    elif opaque_corners(im):
        print(f'  ! {fid}: fundo não é transparente - rode com --knockout ou peça de novo')
    box = im.getchannel('A').getbbox()
    if not box:
        print(f'  ! {fid}: imagem toda transparente, pulando')
        return None
    return im.crop(box)


def process(fid, src, out, clear):
    im = load(fid, src, clear)
    if im is None:
        return
    im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
    im.save(out, 'WEBP', quality=90, method=6)
    print(f'  + {fid}: {out.relative_to(ROOT)}')


def process_icon(aid, src, out, clear):
    im = load(aid, src, clear)
    if im is None:
        return
    side = max(im.size)
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    square.resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS).save(out, 'WEBP', quality=90, method=6)
    print(f'  + {aid}: {out.relative_to(ROOT)}')


def stale(src, out, force):
    return src.exists() and (force or not out.exists() or out.stat().st_mtime < src.stat().st_mtime)


def js_list(ids):
    return '[\n' + ''.join(f"  '{i}',\n" for i in ids) + ']'


def main(args):
    force = '--force' in args
    clear = '--knockout' in args
    ids, actions = form_ids(), action_ids()
    ICONS.mkdir(parents=True, exist_ok=True)

    for fid in ids:
        src, out = SOURCE / f'{fid}.png', PET / f'{fid}.webp'
        if stale(src, out, force):
            process(fid, src, out, clear)
    for aid in actions:
        src, out = ICON_SOURCE / f'{aid}.png', ICONS / f'{aid}.webp'
        if stale(src, out, force):
            process_icon(aid, src, out, clear)

    done = [fid for fid in ids if (PET / f'{fid}.webp').exists()]
    icons = [aid for aid in actions if (ICONS / f'{aid}.webp').exists()]
    MANIFEST.write_text(
        '/** Generated by tools/sprites.py - forms and actions that have their own art. Do not edit. */\n'
        f'export const SPRITES = {js_list(done)};\n\n'
        f'export const ICON_ART = {js_list(icons)};\n',
        encoding='utf-8')

    for label, have, want in (('sprites', done, ids), ('ícones', icons, actions)):
        missing = [i for i in want if i not in have]
        print(f'\n{len(have)}/{len(want)} {label} prontos.' + (' Faltam: ' + ', '.join(missing) if missing else ''))


if __name__ == '__main__':
    main(sys.argv[1:])
